-- Printex Estimasi Supabase connection v2
-- All shared data is available to active staff members only.
-- Create Auth users first, then add their UUIDs to public.staff_members.

create table if not exists public.staff_members (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.price_catalog (
  id bigint generated by default as identity primary key,
  category text not null,
  name text not null,
  price numeric(14,2) not null default 0 check (price >= 0),
  unit text not null default 'pcs',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint price_catalog_category_name_key unique (category, name)
);

create table if not exists public.estimates (
  estimate_number text primary key,
  customer_name text not null default '',
  estimate_date date,
  total numeric(14,2) not null default 0 check (total >= 0),
  paid_amount numeric(14,2) not null default 0 check (paid_amount >= 0),
  payment_status text not null default 'unpaid'
    check (payment_status in ('unpaid','dp','paid_full')),
  data jsonb not null default '{}'::jsonb,
  archived boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  estimate_number text not null references public.estimates(estimate_number) on delete restrict,
  amount numeric(14,2) not null check (amount > 0),
  paid_at timestamptz not null default now(),
  method text,
  reference text,
  notes text,
  recorded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.estimate_sequences (
  estimate_date date primary key,
  last_value integer not null default 0 check (last_value >= 0)
);

create index if not exists estimates_updated_at_idx on public.estimates(updated_at desc);
create index if not exists estimates_created_by_idx on public.estimates(created_by);
create index if not exists payments_recorded_by_idx on public.payments(recorded_by);
create index if not exists estimates_customer_name_idx on public.estimates using gin (to_tsvector('simple', customer_name));
create index if not exists payments_estimate_number_idx on public.payments(estimate_number, paid_at desc);
create index if not exists price_catalog_active_category_idx on public.price_catalog(is_active, category);

alter table public.staff_members enable row level security;
alter table public.price_catalog enable row level security;
alter table public.estimates enable row level security;
alter table public.payments enable row level security;
alter table public.estimate_sequences enable row level security;

drop policy if exists "staff can read own membership" on public.staff_members;
create policy "staff can read own membership" on public.staff_members
for select to authenticated using (user_id = (select auth.uid()) and active);

drop policy if exists "active staff read catalog" on public.price_catalog;
create policy "active staff read catalog" on public.price_catalog for select to authenticated
using (exists (select 1 from public.staff_members m where m.user_id = (select auth.uid()) and m.active));
drop policy if exists "active staff insert catalog" on public.price_catalog;
create policy "active staff insert catalog" on public.price_catalog for insert to authenticated
with check (exists (select 1 from public.staff_members m where m.user_id = (select auth.uid()) and m.active));
drop policy if exists "active staff update catalog" on public.price_catalog;
create policy "active staff update catalog" on public.price_catalog for update to authenticated
using (exists (select 1 from public.staff_members m where m.user_id = (select auth.uid()) and m.active))
with check (exists (select 1 from public.staff_members m where m.user_id = (select auth.uid()) and m.active));

drop policy if exists "active staff read estimates" on public.estimates;
create policy "active staff read estimates" on public.estimates for select to authenticated
using (exists (select 1 from public.staff_members m where m.user_id = (select auth.uid()) and m.active));
drop policy if exists "active staff insert estimates" on public.estimates;
create policy "active staff insert estimates" on public.estimates for insert to authenticated
with check (exists (select 1 from public.staff_members m where m.user_id = (select auth.uid()) and m.active)
  and (created_by is null or created_by = (select auth.uid())));
drop policy if exists "active staff update estimates" on public.estimates;
create policy "active staff update estimates" on public.estimates for update to authenticated
using (exists (select 1 from public.staff_members m where m.user_id = (select auth.uid()) and m.active))
with check (exists (select 1 from public.staff_members m where m.user_id = (select auth.uid()) and m.active));

drop policy if exists "active staff read payments" on public.payments;
create policy "active staff read payments" on public.payments for select to authenticated
using (exists (select 1 from public.staff_members m where m.user_id = (select auth.uid()) and m.active));
drop policy if exists "active staff insert payments" on public.payments;
create policy "active staff insert payments" on public.payments for insert to authenticated
with check (exists (select 1 from public.staff_members m where m.user_id = (select auth.uid()) and m.active)
  and (recorded_by is null or recorded_by = (select auth.uid())));
-- No client UPDATE or DELETE policies for payments: payment history is append-only.

grant select on public.staff_members to authenticated;
grant select, insert, update on public.price_catalog to authenticated;
grant select, insert, update on public.estimates to authenticated;
grant select, insert on public.payments to authenticated;
grant usage, select on sequence public.price_catalog_id_seq to authenticated;
grant usage, select on sequence public.payments_id_seq to authenticated;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated;

